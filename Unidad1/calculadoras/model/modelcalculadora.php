<?php
class Model{
    public function suma($num1,$num2){
        return $num1+$num2;
    }
    public function resta($num1,$num2){
        return $num1-$num2;
    }
    public function multiplicar($num1,$num2){
        return $num1*$num2;
    }
    public function division($num1,$num2){
        return $num1/$num2;
    }
}
?>